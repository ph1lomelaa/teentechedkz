"""Схемы матрицы прав (Этап 2.1).

Почему клетка считается на сервере
----------------------------------
Реестр хранит правило в «свёрнутом» виде: набор разрешённых ролей плюс словарь
скоупов, где перечислены только отличия от `Scope.all`. Отдать эту форму как
есть — значит заставить фронт повторить у себя правило «роль, которой нет в
`scope`, получает весь раздел». Это ровно тот дубликат, из-за которого матрица
однажды разойдётся с поведением и начнёт показывать красивую неправду.

Поэтому сервер разворачивает правило в готовые клетки «роль → решение»,
вызывая те же `allows()` и `scope_for()`, что и эндпоинты. Матрица получается
истинной по построению: она не пересказывает реестр, а спрашивает его.
"""
from __future__ import annotations

from pydantic import BaseModel

from app.core.permissions import Action, Scope
from app.models.user import UserRole


class RoleCell(BaseModel):
    """Одна клетка: что эта роль может с этой парой «ресурс + действие»."""

    allowed: bool

    #: Заполнен только у разрешённой роли. У запрещённой скоупа нет: `scope_for`
    #: вернул бы для неё `all` (значение по умолчанию), и клетка «нельзя, но
    #: весь раздел» читалась бы как разрешение.
    scope: Scope | None = None


class MatrixRule(BaseModel):
    """Строка матрицы — правило реестра, развёрнутое по всем ролям."""

    resource: str
    action: Action
    roles: dict[UserRole, RoleCell]

    #: None означает «регламентом не зафиксировано» — сигнал, а не пропуск.
    basis: str | None = None

    #: Условия, которые в клетку не влезают. Страница рисует «+N доп. правил».
    extra_rules: list[str] = []

    #: Как выглядит отказ. `error_code` — то, что реально уедет во фронт
    #: заголовком X-Error-Code, поэтому он виден в матрице, а не только в коде.
    denied_detail: str | None = None
    error_code: str

    #: Заполнено там, где поведение расходится с ожиданием. Миграция такие места
    #: сохранила намеренно — страница помечает их «требует решения».
    review: str | None = None

    #: Правило нельзя переключать: без него нельзя управлять системой. Страница
    #: показывает такую строку без переключателей, а не прячет — иначе админ
    #: будет искать пропавшее право.
    locked: bool = False

    #: Состав ролей изменён из конструктора, а не взят из кода. Показывается
    #: пометкой: иначе непонятно, почему поведение расходится с исходным.
    is_overridden: bool = False


class MatrixSummary(BaseModel):
    """Счётчики для ряда StatCard. Считает сервер — чтобы «требует решения»
    везде означало одно и то же.

    Условия считаются двумя числами намеренно: правил с условиями 29, а самих
    условий 50 — одно правило нередко несёт несколько. Одно поле под обоими
    смыслами читалось бы как угодно.
    """

    resources: int
    rules: int
    needs_review: int

    #: Сколько правил несут хотя бы одно условие сверх «роль × действие × скоуп».
    rules_with_extra: int

    #: Сколько всего таких условий — сумма пометок «+N доп. правил» по странице.
    extra_rules: int


class PermissionMatrix(BaseModel):
    """Весь реестр целиком.

    `roles` и `actions` едут вместе с правилами, чтобы порядок колонок задавал
    сервер: он же владеет и порядком объявления правил.
    """

    roles: list[UserRole]
    actions: list[Action]
    resources: list[str]
    rules: list[MatrixRule]
    summary: MatrixSummary
