"""Кого вообще можно назначить на роль в «Команде ученика».

Правило одно на всю систему и раньше существовало в трёх несогласованных
копиях: `ROLE_USER_SOURCE` на фронте наполнял выпадашку строго по `users.role`,
`_BOARD_STAFF_ROLE` на бэкенде — колонки доски распределения, а сама доска
дополнительно фильтровала по специализации. Из-за этого выпадашка и доска
предлагали для одной роли разных людей, а МЗК-менеджер, у которого в учётке
стояла роль «Ментор», не попадал в список МЗК вообще — при том что назначить
его бэкенд разрешал.

Здесь оно живёт целиком, и от него читают оба экрана.
"""

from __future__ import annotations

from sqlalchemy import Select, or_, select

from app.models.mentor_assignment import MentorRole
from app.models.user import User, UserRole

# Роли, для которых пул кандидатов берётся не из менторов. МЗК ведёт студента
# целиком, и назначают на неё менеджера; всё, чего нет в карте, — менторы.
_STAFF_ROLE: dict[MentorRole, UserRole] = {
    MentorRole.mzk: UserRole.mzk_manager,
}


def staff_role_for(role: MentorRole) -> UserRole:
    """Учётная роль, которая «по должности» соответствует роли назначения."""
    return _STAFF_ROLE.get(role, UserRole.mentor)


def candidates_query(role: MentorRole) -> Select:
    """Запрос кандидатов на роль, отсортированный по имени.

    Кандидат — активный сотрудник, для которого верно хотя бы одно:

    * роль заявлена в его специализациях (`mentor_specialties`) — основной путь,
      он и позволяет вести МЗК человеку с учётной ролью ментора и наоборот;
    * его учётная роль соответствует роли назначения по должности;
    * он админ — в небольшой команде админ ведёт студентов сам, и назначать его
      бэкенд разрешает (`_load_assignable_mentor`), так что прятать его из
      списка значило показывать не то, что система на самом деле умеет.

    `is_active` здесь не опция: уволенный сотрудник не должен предлагаться к
    назначению. В уже существующих назначениях он остаётся видимым — карточка
    студента читает их из `responsibles`, а не отсюда.

    Специализация не проверяется при самом назначении (`_load_assignable_mentor`)
    и здесь тоже не отсекает: это подсказка, кому роль подходит, а не запрет.
    Поэтому пул шире одной специализации — подстраховать коллегу на время
    отпуска нужно уметь без похода в настройки.
    """
    return (
        select(User)
        .where(
            User.is_active == True,  # noqa: E712
            or_(
                User.mentor_specialties.any(role.value),
                User.role == staff_role_for(role),
                User.role == UserRole.admin,
            ),
        )
        .order_by(User.name)
    )
