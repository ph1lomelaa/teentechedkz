import { User, UserRole } from '@/types'

/**
 * Единственная правда о том, куда роль попадает по умолчанию.
 *
 * Раньше у ментора было три разных «дома» в зависимости от того, как он вошёл:
 * обычный логин вёл в CRM на /my-students, смена временного пароля — на
 * /workspace, подпись регламента — на /workspace/my-day. Три пути в одну роль
 * читались как «интерфейс поменялся сам», поэтому дом у роли ровно один.
 */
export function getDefaultPath(role: UserRole): string {
  switch (role) {
    case 'admin':
      return '/dashboard'
    case 'mentor':
      // Общая база, а не «Мой день»: на старте у ментора ещё нет ни назначенных
      // студентов, ни задач, и кабинет встречал бы его пустым экраном — худшее
      // первое впечатление от системы. В базе он сразу видит, с кем работает
      // компания. Скоуп при этом никуда не делся: список фильтрует
      // mentor_scope.py на бэкенде.
      return '/students'
    case 'mzk_manager':
      // Менеджер остаётся в кабинете: «Мой день» собирает его просрочки,
      // горящий SLA и встречи, и у него это всё есть с первого дня.
      return '/workspace/my-day'
    case 'student':
      return '/portal'
    default:
      return '/dashboard'
  }
}

/**
 * Куда вести сразу после успешного входа.
 *
 * Порядок «ворот» тот же, что в `useBaseAuthGuard` и в `core/deps.py`: сначала
 * неоткрытый аккаунт, потом временный пароль, потом дом роли. Отдельная функция
 * — чтобы правило не расползлось по экранам входа: ровно на этом уже обжигались
 * (см. докстринг `getDefaultPath`), и логин без неё уводил бы ждущего одобрения
 * в рабочий раздел, откуда его тут же разворачивает гейт.
 *
 * Подпись регламента сюда не входит: она зависит от того, откуда человек шёл,
 * и решается в `useBaseAuthGuard`, где есть текущий маршрут.
 */
export function postLoginPath(
  user: Pick<User, 'role' | 'must_change_password'> & { is_active?: boolean },
): string {
  // Строго `=== false`, а не `!user.is_active`. Отсутствующее поле не должно
  // считаться «аккаунт закрыт»: сбой формы payload запер бы на экране ожидания
  // всех сразу. Настоящая защита стоит на бэкенде (core/deps.py) — здесь
  // решается только удобство маршрута, и ошибка в сторону «пустить» стоит
  // максимум одного 403, а ошибка в сторону «запереть» кладёт вход целиком.
  if (user.is_active === false) return '/pending'
  if (user.must_change_password) return '/change-password'
  return getDefaultPath(user.role)
}

/**
 * Куда вернуть человека после экрана-«ворот» (подпись регламента), когда
 * неизвестно, откуда он пришёл.
 *
 * Сейчас совпадает с getDefaultPath для всех ролей — отдельное имя оставлено
 * потому, что это другой вопрос: не «где твой дом», а «куда тебя вернуть после
 * принудительного экрана». Если однажды они разойдутся, разойдутся здесь.
 */
export function workspaceHomeFor(role: UserRole | undefined): string {
  if (!role) return '/'
  return getDefaultPath(role)
}
